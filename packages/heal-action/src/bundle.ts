// How the action is bundled: one ESM file for GitHub's node24 runtime, every dependency inside
// (workspace packages and zod), nothing minified so the committed bundle can be reviewed.
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/** The action's entry points: the GitHub one, and local mode's (P4.6). */
export const ENTRIES = { "index.mjs": "./action.ts", "local.mjs": "./local.ts" } as const;

export async function bundleAction(entry: keyof typeof ENTRIES = "index.mjs"): Promise<string> {
  const result = await build({
    entryPoints: [fileURLToPath(new URL(ENTRIES[entry], import.meta.url))],
    // Module comments name paths from here, whatever directory the build runs in.
    absWorkingDir: fileURLToPath(new URL("..", import.meta.url)),
    bundle: true,
    platform: "node",
    target: "node24",
    format: "esm",
    write: false,
    legalComments: "none",
    logLevel: "silent",
    banner: { js: "// Generated by scripts/bundle.ts: don't edit." },
  });
  const [file] = result.outputFiles;
  if (file === undefined) throw new Error("esbuild produced nothing");
  // Line endings as git stores them, whatever the machine (CLAUDE.md: LF everywhere).
  return file.text.replace(/\r\n/g, "\n");
}
